// MARK: - Detection

nonisolated enum SecretDetector {
    static let byContentKey = "detectSecretsByContent"

    /// Bump when `looksLikePassword` changes, so existing items are checked
    /// again once.
    static let contentCheckVersion = 1
    private static let scannedVersionKey = "secretContentCheckScannedVersion"

    static var scannedVersion: Int {
        get { UserDefaults.standard.integer(forKey: scannedVersionKey) }
        set { UserDefaults.standard.set(newValue, forKey: scannedVersionKey) }
    }

    static var detectsByContent: Bool {
        UserDefaults.standard.object(forKey: byContentKey) as? Bool ?? true
    }

    enum Verdict {
        case plain, secret
        /// The source asked for the item not to be kept at all.
        case skip
    }

    // https://nspasteboard.org
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static let passwordManagers: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    static func verdict(
        text: String,
        types: [NSPasteboard.PasteboardType],
        sourceBundleID: String?,
        byContent: Bool
    ) -> Verdict {
        if types.contains(transientType) { return .skip }
        if types.contains(concealedType) || types.contains(autoGeneratedType) { return .secret }
        if let sourceBundleID, passwordManagers.contains(sourceBundleID) { return .secret }
        if byContent, looksLikePassword(text) { return .secret }
        return .plain
    }

    /// A single "word" of 8–64 characters mixing at least three of lower case,
    /// upper case, digits and symbols, that isn't a URL, path, email, domain,
    /// UUID or hex hash. Also catches most API keys and tokens.
    static func looksLikePassword(_ text: String) -> Bool {
        guard (8...64).contains(text.count),
              !text.contains(where: \.isWhitespace),
              !text.contains("://"),
              !text.hasPrefix("/"), !text.hasPrefix("~")
        else { return false }

        let excluded = [
            #"^[^@]+@[^@]+\.[A-Za-z]{2,}$"#,
            #"^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$"#,
            #"^[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}$"#,
            #"^[0-9A-Fa-f]+$"#,
        ]
        if excluded.contains(where: { text.range(of: $0, options: .regularExpression) != nil }) {
            return false
        }

        var classes = 0
        if text.contains(where: \.isLowercase) { classes += 1 }
        if text.contains(where: \.isUppercase) { classes += 1 }
        if text.contains(where: \.isNumber) { classes += 1 }
        if text.contains(where: { !$0.isLetter && !$0.isNumber }) { classes += 1 }
        return classes >= 3
    }
}

// MARK: - Encryption

/// The key lives in the login keychain, which needs no Apple team signing but
/// can't require Touch ID itself; `SecretVault` does that in the app instead.
nonisolated final class SecretCipher {
    enum CipherError: Error {
        case keychain(OSStatus)
        case invalidData
    }

    private let service: String
    private let account = "secrets-key"
    /// Shown as the item's kind in Keychain Access instead of "application
    /// password".
    private let kind = "encryption key"
    private var cachedKey: SymmetricKey?

    init(service: String = Bundle.main.bundleIdentifier ?? "dev.local.Cliphoard") {
        self.service = service
    }

    func encrypt(_ text: String) throws -> Data {
        guard let data = try AES.GCM.seal(Data(text.utf8), using: key(createIfMissing: true)).combined else {
            throw CipherError.invalidData
        }
        return data
    }

    func decrypt(_ data: Data) throws -> String {
        let box = try AES.GCM.SealedBox(combined: data)
        let plain = try AES.GCM.open(box, using: key(createIfMissing: false))
        guard let text = String(data: plain, encoding: .utf8) else { throw CipherError.invalidData }
        return text
    }

    /// Decrypting never creates a key: a new one couldn't open anything.
    private func key(createIfMissing: Bool) throws -> SymmetricKey {
        if let cachedKey { return cachedKey }
        guard let key = try loadKey() ?? (createIfMissing ? createKey() : nil) else {
            throw CipherError.keychain(errSecItemNotFound)
        }
        cachedKey = key
        return key
    }

    private var baseQuery: [String: Any] {
        [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account,
            kSecUseDataProtectionKeychain as String: false,
        ]
    }

    private func loadKey() throws -> SymmetricKey? {
        var query = baseQuery
        query[kSecReturnData as String] = true
        query[kSecReturnAttributes as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne
        var result: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &result)
        switch status {
        case errSecSuccess:
            guard let item = result as? [String: Any],
                  let data = item[kSecValueData as String] as? Data
            else { throw CipherError.invalidData }
            if item[kSecAttrDescription as String] as? String != kind {
                let update = [kSecAttrDescription as String: kind]
                SecItemUpdate(baseQuery as CFDictionary, update as CFDictionary)
            }
            return SymmetricKey(data: data)
        case errSecItemNotFound:
            return nil
        default:
            throw CipherError.keychain(status)
        }
    }

    private func createKey() throws -> SymmetricKey {
        let key = SymmetricKey(size: .bits256)
        var item = baseQuery
        item[kSecValueData as String] = key.withUnsafeBytes { Data($0) }
        item[kSecAttrLabel as String] = "Cliphoard secrets key"
        item[kSecAttrDescription as String] = kind
        let status = SecItemAdd(item as CFDictionary, nil)
        guard status == errSecSuccess else { throw CipherError.keychain(status) }
        return key
    }
}

// MARK: - Unlocking

/// After Touch ID or the password, secrets stay available for a few minutes,
/// until the screen locks or the Mac sleeps.
@Observable
final class SecretVault {
    static let unlockDuration: TimeInterval = 5 * 60

    private(set) var unlockedUntil: Date?

    @ObservationIgnored private var observers: [NSObjectProtocol] = []

    var isUnlocked: Bool {
        unlockedUntil.map { $0 > .now } ?? false
    }

    init() {
        let lock: @Sendable (Notification) -> Void = { [weak self] _ in
            MainActor.assumeIsolated { self?.lock() }
        }
        observers = [
            DistributedNotificationCenter.default().addObserver(
                forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main, using: lock
            ),
            NSWorkspace.shared.notificationCenter.addObserver(
                forName: NSWorkspace.willSleepNotification, object: nil, queue: .main, using: lock
            ),
        ]
    }

    /// `reason` completes "Cliphoard is trying to …".
    func authorize(_ reason: String) async -> Bool {
        if isUnlocked { return true }
        let context = LAContext()
        do {
            guard try await context.evaluatePolicy(.deviceOwnerAuthentication, localizedReason: reason) else {
                return false
            }
        } catch {
            return false
        }
        unlockedUntil = .now.addingTimeInterval(Self.unlockDuration)
        return true
    }

    func lock() {
        unlockedUntil = nil
    }
}
